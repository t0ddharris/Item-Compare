def release_paths(variant='default'):
    assert variant in VARIANTS, variant
    work = ROOT if variant == 'default' else ROOT/'variants'/variant
    suffix = '' if variant == 'default' else '-RussianHeading'
    return work, SOURCE_ROOT.parent/'releases'/f'ItemCompare-v{VERSION}{suffix}'


def read(path):
    return json.loads(path.read_text(encoding='utf-8-sig'))


def write(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, indent=2), encoding='utf-8')


def walk(v):
    if isinstance(v, dict):
        yield v
        for c in v.values():
            yield from walk(c)
    elif isinstance(v, list):
        for c in v:
            yield from walk(c)


def rename(v, old, new):
    if isinstance(v, str): return v.replace(old, new)
    if isinstance(v, list): return [rename(x, old, new) for x in v]
    if isinstance(v, dict): return {k: rename(x, old, new) for k, x in v.items()}
    return v


def ex(kind, **kw):
    return {'$type': f'UAssetAPI.Kismet.Bytecode.Expressions.EX_{kind}, UAssetAPI', **kw}


def ptr(name=None, owner=0):
    return {'$type': 'UAssetAPI.Kismet.Bytecode.KismetPropertyPointer, UAssetAPI',
            'New': {'$type': 'UAssetAPI.UnrealTypes.FFieldPath, UAssetAPI',
                    'Path': [name] if name else [], 'ResolvedOwner': owner}}


def var(name, owner, local=False):
    return ex('LocalVariable' if local else 'InstanceVariable', Variable=ptr(name, owner))


def size(e):
    k = e['$type'].split('EX_')[1].split(',')[0]
    if k in ('InstanceVariable', 'LocalVariable', 'LocalOutVariable', 'ObjectConst'): return 9
    if k in ('Nothing', 'EndOfScript', 'Self', 'True', 'False', 'NoObject', 'IntZero', 'IntOne'): return 1
    if k in ('IntConst', 'FloatConst', 'Jump'): return 5
    if k == 'ByteConst': return 2
    if k == 'StringConst': return 2 + len(e['Value'].encode('ascii'))
    if k == 'UnicodeStringConst': return 3 + len(e['Value'].encode('utf-16-le'))
    if k == 'Return': return 1 + size(e['ReturnExpression'])
    if k == 'Context': return 13 + size(e['ObjectExpression']) + size(e['ContextExpression'])
    if k in ('LocalVirtualFunction', 'VirtualFunction'): return 14 + sum(map(size, e['Parameters']))
    if k in ('FinalFunction', 'LocalFinalFunction', 'CallMath'): return 10 + sum(map(size, e['Parameters']))
    if k == 'Let': return 9 + size(e['Variable']) + size(e['Expression'])
    if k in ('LetObj', 'LetBool'): return 1 + size(e['VariableExpression']) + size(e['AssignmentExpression'])
    if k == 'LetValueOnPersistentFrame': return 9 + size(e['AssignmentExpression'])
    if k == 'JumpIfNot': return 5 + size(e['BooleanExpression'])
    if k == 'StructConst': return 14 + sum(map(size, e['Value']))
    raise ValueError(f'Unsupported generated bytecode: {k}')


def ctx(obj, inner, result=None):
    return ex('Context', ObjectExpression=obj, Offset=size(inner), PropertyType=0,
              RValuePointer=result or ptr(), ContextExpression=inner)


def call(name, *args):
    return ex('LocalVirtualFunction', VirtualFunctionName=name, Parameters=list(args))


def prop(name, value, kind='Objects.ObjectPropertyData', **kw):
    return {'$type': f'UAssetAPI.PropertyTypes.{kind}, UAssetAPI', 'Name': name,
            'ArrayIndex': 0, 'PropertyGuid': None, 'IsZero': False,
            'PropertyTagFlags': 'None', 'PropertyTypeName': None,
            'PropertyTagExtensions': 'NoExtension', 'Value': value, **kw}


def struct(name, kind, value):
    return prop(name, value, 'Structs.StructPropertyData', StructType=kind,
                SerializeNone=True, StructGUID='{00000000-0000-0000-0000-000000000000}',
                SerializationControl='NoExtension', Operation='None')


def vector(name, x, y):
    return struct(name, 'Vector2D', [prop(name, {
        '$type': 'UAssetAPI.UnrealTypes.FVector2D, UAssetAPI', 'X': x, 'Y': y},
        'Structs.Vector2DPropertyData')])


def enum(name, kind, value):
    return prop(name, value, 'Objects.EnumPropertyData', EnumType=kind, InnerType='ByteProperty')


class Asset:
    def __init__(self, data): self.data = data
    def export(self, name): return next(e for e in self.data['Exports'] if e['ObjectName'] == name)
    def index(self, name): return self.data['Exports'].index(self.export(name)) + 1
    def imp(self, name): return -1 - next(i for i,e in enumerate(self.data['Imports']) if e['ObjectName'] == name)
    def add_import(self, name, outer, cp='/Script/CoreUObject', cn='Object'):
        for i,e in enumerate(self.data['Imports']):
            if e['ObjectName'] == name and e['OuterIndex'] == outer: return -1-i
        self.data['Imports'].append({'$type': 'UAssetAPI.Import, UAssetAPI', 'ObjectName': name,
            'OuterIndex': outer, 'ClassPackage': cp, 'ClassName': cn,
            'PackageName': None, 'bImportOptional': False})
        return -len(self.data['Imports'])
    def append(self, export):
        self.data['Exports'].append(export)
        return len(self.data['Exports'])
    def names(self):
        # UAssetAPI writes the name map before the export data. Collect every
        # added serialized name before encoding; private names must be exported.
        for node in walk(self.data):
            for key in ('Name', 'ObjectName', 'VirtualFunctionName', 'FunctionName', 'ClassName',
                        'ClassPackage', 'StructType', 'EnumType'):
                value = node.get(key)
                if isinstance(value, str) and value not in self.data['NameMap']:
                    self.data['NameMap'].append(value)
            if 'Path' in node and 'ResolvedOwner' in node:
                for value in node['Path']:
                    if value not in self.data['NameMap']: self.data['NameMap'].append(value)
            if any(t in node.get('$type','') for t in ('EnumPropertyData,','NamePropertyData,')):
                value = node['Value']
                if isinstance(value,str) and value not in self.data['NameMap']: self.data['NameMap'].append(value)
        self.data['NamesReferencedFromExportDataCount'] = len(self.data['NameMap'])


def getprop(export, name): return next(p for p in export['Data'] if p['Name'] == name)


def widget(a, template, name, cls, cdo, outer, data):
    e = copy.deepcopy(template)
    e.update(ObjectName=name, ClassIndex=cls, TemplateIndex=cdo, OuterIndex=outer,
             SerialSize=0, SerialOffset=0, Data=data,
             SerializationBeforeSerializationDependencies=[],
             CreateBeforeSerializationDependencies=[],
             SerializationBeforeCreateDependencies=[cls, cdo],
             CreateBeforeCreateDependencies=[outer])
    # Dependencies are references to objects, never numeric layout values.
    e['CreateBeforeSerializationDependencies'] = sorted({n['Value'] for n in walk(data)
        if 'Objects.ObjectPropertyData,' in n.get('$type', '') and n['Value']})
    return a.append(e)


def build_assets(variant='default'):
    original = read(ROOT/'decoded/tooltip.json')
    a = Asset(rename(original, ORIGINAL, PRIVATE))
    # The class name is also a prefix of WarningLabel/Stat_Custom dependencies.
    # Those are original external assets, not part of the private class rename.
    a.data['Imports'] = copy.deepcopy(original['Imports'])
    cls = a.export(PRIVATE+'_C')
    owner, tree = a.index(PRIVATE+'_C'), a.index('WidgetTree')
    umg = a.imp('/Script/UMG')
    widget_class = a.add_import('Widget', umg, cn='Class')
    canvas_class = a.add_import('CanvasPanel', umg, cn='Class')
    canvas_cdo = a.add_import('Default__CanvasPanel', umg, cp='/Script/UMG', cn='CanvasPanel')
    anchor_class = a.add_import('MenuAnchor', umg, cn='Class')
    anchor_cdo = a.add_import('Default__MenuAnchor', umg, cp='/Script/UMG', cn='MenuAnchor')
    popup_open = a.add_import('Open', anchor_class)
    popup_close = a.add_import('Close', anchor_class)
    remove_from_parent = a.add_import('RemoveFromParent', widget_class)
    overlay_class, overlay_cdo = a.imp('Overlay'), a.imp('Default__Overlay')
    set_visibility = a.add_import('SetVisibility', widget_class)
    stock_pkg = '/Game/_Dawnwalker/UI/_Unified/GameHub/Inventory/Tooltip/'+ORIGINAL
    pkg = a.add_import(stock_pkg, 0, cn='Package')
    stock_class = a.add_import(ORIGINAL+'_C', pkg, cp='/Script/UMG', cn='WidgetBlueprintGeneratedClass')
    stock_cdo = a.add_import('Default__'+ORIGINAL+'_C', pkg, cp=stock_pkg, cn=ORIGINAL+'_C')

    # A canvas with auto-sized children can contribute their size to an overlay.
    # Force the comparison branch to report zero desired size in BOTH axes.
    # Fill-aligned slots still allot it the main card's full geometry, allowing
    # right/center anchors without changing the inventory's layout measurements.
    template = a.export('Overlay_0')
    overlay = widget(a, template, 'IC_Root', overlay_class, overlay_cdo, tree, [])
    layer = widget(a, template, 'IC_ComparisonLayer', canvas_class, canvas_cdo, tree,
                   [enum('Visibility', 'ESlateVisibility', 'Collapsed'),
                    prop('bIsVariable', True, 'Objects.BoolPropertyData')])
    isolation = widget(a, template, 'IC_LayoutIsolation', a.imp('SizeBox'),
        a.imp('Default__SizeBox'), tree, [
            prop('WidthOverride',0.0,'Objects.FloatPropertyData'),
            prop('HeightOverride',0.0,'Objects.FloatPropertyData'),
            prop('bOverride_WidthOverride',True,'Objects.BoolPropertyData'),
            prop('bOverride_HeightOverride',True,'Objects.BoolPropertyData'),
            enum('Visibility','ESlateVisibility','HitTestInvisible')])
    vertical_class, vertical_cdo = a.imp('VerticalBox'), a.imp('Default__VerticalBox')
    stack = widget(a,template,'IC_Stack',vertical_class,vertical_cdo,tree,[
        prop('bIsVariable',True,'Objects.BoolPropertyData'),
        enum('Visibility','ESlateVisibility','HitTestInvisible')])
    # SMenuAnchor defers this popup's paint until after window content, so a
    # later-painted hub sibling (such as Better Quickslots) cannot cover it.
    # It neither joins the application menu stack nor requests keyboard focus.
    anchor = widget(a,template,'IC_PopupAnchor',anchor_class,anchor_cdo,tree,[
        prop('bIsVariable',True,'Objects.BoolPropertyData'),
        enum('Visibility','ESlateVisibility','HitTestInvisible'),
        enum('Placement','EMenuPlacement','MenuPlacement_RightLeftCenter'),
        prop('bFitInWindow',False,'Objects.BoolPropertyData'),
        prop('ShouldDeferPaintingAfterWindowContent',True,'Objects.BoolPropertyData'),
        prop('UseApplicationMenuStack',False,'Objects.BoolPropertyData')])
    header_template=a.export('ItemCategoryLabel')
    header_data=copy.deepcopy(header_template['Data'])
    header_data=[p for p in header_data if p['Name'] not in ('Slot','ColorAndOpacity')]
    next(p for p in header_data if p['Name']=='Text')['CultureInvariantString']='EQUIPPED'
    next(p for p in header_data if p['Name']=='bIsVariable')['Value']=False
    header=widget(a,header_template,'IC_EquippedLabel',header_template['ClassIndex'],
        header_template['TemplateIndex'],tree,header_data)
    cards,groups = [],[]
    for i in range(2):
        groups.append(widget(a,template,f'IC_Group{i}',vertical_class,vertical_cdo,tree,
            [enum('Visibility','ESlateVisibility','Collapsed'),prop('bIsVariable',True,'Objects.BoolPropertyData')]))
        cards.append(widget(a,template,f'IC_EquippedTooltip{i}',stock_class,stock_cdo,tree,
            [enum('Visibility','ESlateVisibility','HitTestInvisible'),prop('bIsVariable',True,'Objects.BoolPropertyData')]))

    def slot(name, parent, child, kind, data=()):
        clsidx, cdoidx = a.imp(kind), a.imp('Default__'+kind)
        idx = widget(a, a.export('CanvasPanelSlot_0'), name, clsidx, cdoidx, parent,
                     list(data)+[prop('Parent',parent), prop('Content',child)])
        child_exp = a.data['Exports'][child-1]
        child_exp['Data'] = [p for p in child_exp['Data'] if p['Name'] != 'Slot']+[prop('Slot',idx)]
        child_exp['CreateBeforeSerializationDependencies'].append(idx)
        return idx

    old_root = a.index('VerticalBox_0')
    fill = [enum('HorizontalAlignment','EHorizontalAlignment','HAlign_Fill'),
            enum('VerticalAlignment','EVerticalAlignment','VAlign_Fill')]
    slots = [slot('IC_MainSlot', overlay, old_root, 'OverlaySlot', fill),
             slot('IC_LayerSlot', overlay, isolation, 'OverlaySlot', fill)]
    isolation_slot = slot('IC_IsolationSlot',isolation,layer,'SizeBoxSlot',fill)
    isolation_exp=a.data['Exports'][isolation-1]
    isolation_exp['Data'].append(prop('Slots',[prop('0',isolation_slot)],
        'Objects.ArrayPropertyData',ArrayType='ObjectProperty'))
    isolation_exp['CreateBeforeSerializationDependencies'].append(isolation_slot)
    root_exp = a.data['Exports'][overlay-1]
    root_exp['Data'] = [prop('Slots',[prop(str(i),s) for i,s in enumerate(slots)],
                              'Objects.ArrayPropertyData', ArrayType='ObjectProperty')]
    root_exp['CreateBeforeSerializationDependencies'] = slots
    # Dawnwalker 1.1 replaced the enclosing ScaleBox with a scrollable card.
    # Wrap its existing root, preserving the entire stock scrolling subtree.
    tree_export=a.export('WidgetTree')
    assert getprop(tree_export,'RootWidget')['Value']==old_root
    getprop(tree_export,'RootWidget')['Value']=overlay
    tree_export['CreateBeforeSerializationDependencies']=[
        overlay if i==old_root else i for i in tree_export['CreateBeforeSerializationDependencies']]

    def anchored(y, x=24.0):
        return [struct('LayoutData','AnchorData',[
            struct('Offsets','Margin', [prop('Left',x,'Objects.FloatPropertyData'),
                                      prop('Top',y,'Objects.FloatPropertyData')]),
            struct('Anchors','Anchors',[vector('Minimum',1.0,0.5), vector('Maximum',1.0,0.5)]),
            vector('Alignment',0.0,0.5)]), prop('bAutoSize',True,'Objects.BoolPropertyData')]
    # Keep the stack in the template tree until widget variables are bound.
    # The popup content provider detaches it on first use; IC_Stack's strong
    # instance reference then retains it for subsequent open/close cycles.
    canvas_slots = [slot('IC_StorageSlot',layer,stack,'CanvasPanelSlot',anchored(0.0)),
                    slot('IC_StackSlot',layer,anchor,'CanvasPanelSlot',anchored(0.0))]
    layer_exp = a.data['Exports'][layer-1]
    layer_exp['Data'].append(prop('Slots',[prop(str(i),s) for i,s in enumerate(canvas_slots)],
                                   'Objects.ArrayPropertyData',ArrayType='ObjectProperty'))
    layer_exp['CreateBeforeSerializationDependencies'].extend(canvas_slots)

    def set_slots(idx, indices):
        e=a.data['Exports'][idx-1]
        e['Data'].append(prop('Slots',[prop(str(i),s) for i,s in enumerate(indices)],
            'Objects.ArrayPropertyData',ArrayType='ObjectProperty'))
        e['CreateBeforeSerializationDependencies'].extend(indices)
    group_slots=[slot('IC_HeaderSlot',stack,header,'VerticalBoxSlot',[
        struct('Padding','Margin',[prop('Left',30.0,'Objects.FloatPropertyData'),
                                   prop('Top',12.0,'Objects.FloatPropertyData'),
                                   prop('Bottom',8.0,'Objects.FloatPropertyData')])])]
    for i in range(2):
        group_slots.append(slot(f'IC_GroupSlot{i}',stack,groups[i],'VerticalBoxSlot',[
            struct('Padding','Margin',[prop('Bottom',24.0,'Objects.FloatPropertyData')])]))
        set_slots(groups[i],[slot(f'IC_CardSlot{i}',groups[i],cards[i],'VerticalBoxSlot')])
    set_slots(stack,group_slots)

    members=[('IC_ComparisonLayer',canvas_class),('IC_PopupAnchor',anchor_class),('IC_Stack',vertical_class)]
    for i in range(2): members += [(f'IC_EquippedTooltip{i}',stock_class),(f'IC_Group{i}',vertical_class)]
    for member_name, member_class in members:
        member = copy.deepcopy(next(p for p in cls['LoadedProperties'] if p['Name']=='SizeBox_0'))
        member.update(Name=member_name, PropertyClass=member_class)
        cls['LoadedProperties'].append(member)

    fn_name = 'IC_UpdateComparison'
    fn_owner = len(a.data['Exports'])+1
    templates = {p['Name']: p for p in a.export('Get Currently Equipped Item Custom Stats')['LoadedProperties']}
    slot_templates = {p['Name']: p for p in a.export('GetComparedItemSlot')['LoadedProperties']}
    locals_ = []
    for source, old_name, new_name in [
        (templates,'CallFunc_Get_User_Inventory_Component_ReturnValue','Inventory'),
        (templates,'CallFunc_GetComparedItemSlot_Output','EquipmentSlot'),
        (templates,'CallFunc_GetEquippedItem_ReturnValue','EquippedHandle'),
        (slot_templates,'CallFunc_GetValidSlotsForCurrentItem_ReturnValue','ValidSlots')]:
        p=copy.deepcopy(source[old_name]); p.update(Name=new_name, PropertyFlags='CPF_None')
        if 'Inner' in p: p['Inner']['Name']=new_name
        locals_.append(p)
    has_comparison=copy.deepcopy(next(p for e in a.data['Exports'] for p in e.get('LoadedProperties',[])
        if 'FBoolProperty,' in p['$type']))
    has_comparison.update(Name='HasComparison',PropertyFlags='CPF_None',Value=False)
    locals_.append(has_comparison)
    local = lambda name: var(name,fn_owner,True)
    def store(name, value):
        return ex('Let', Value=ptr(name,fn_owner), Variable=local(name), Expression=value)
    def visible(value, member='IC_ComparisonLayer'):
        return ctx(var(member,owner),ex('FinalFunction',StackNode=set_visibility,
                                                     Parameters=[ex('ByteConst',Value=value)]))
    def math(name, *params): return ex('CallMath',StackNode=a.imp(name),Parameters=list(params))
    def popup(opened):
        return ctx(var('IC_PopupAnchor',owner),ex('FinalFunction',
            StackNode=popup_open if opened else popup_close,
            Parameters=[ex('False')] if opened else []))
    def found(value):
        return ex('LetBool',VariableExpression=local('HasComparison'),
                  AssignmentExpression=ex('True' if value else 'False'))
    # IsValid has two distinct imports. Reuse the observed ItemHandle signature,
    # including its world context, rather than the UObject overload.
    handle_isvalid = next(n['StackNode'] for n in walk(a.export('GetComparedItemSlot')['ScriptBytecode'])
        if 'EX_CallMath,' in n.get('$type','') and len(n.get('Parameters',[]))==2
        and a.data['Imports'][-n['StackNode']-1]['ObjectName']=='IsValid')
    valid_handle = lambda h: ex('CallMath',StackNode=handle_isvalid,Parameters=[ex('Self'),h])
    branches=[]
    body=[popup(False),visible(1),visible(1,'IC_Group0'),visible(1,'IC_Group1'),found(False)]
    def guard(condition):
        branch=ex('JumpIfNot',CodeOffset=0,BooleanExpression=condition)
        branches.append(branch); body.append(branch)
    guard(valid_handle(var('Target Item Handle',owner)))
    body.append(store('Inventory',call('Get User Inventory Component')))
    # Match the stock inventory's equipped predicate, including its search of
    # both day/night loadouts. Gate the entire stack, not just a duplicate card:
    # hovering either equipped ring must not display the other equipped ring.
    equipped=ctx(ex('ObjectConst',Value=a.imp('Default__BFPL_InventoryUI_C')),
        call('Is Item Equipped',local('Inventory'),var('Target Item Handle',owner),
             ex('IntConst',Value=-1),ex('True'),ex('Self')))
    guard(math('Not_PreBool',equipped))
    body.append(store('ValidSlots',call('GetValidSlotsForCurrentItem')))
    length=ctx(ex('ObjectConst',Value=a.imp('Default__KismetArrayLibrary')),
               ex('FinalFunction',StackNode=a.imp('Array_Length'),Parameters=[local('ValidSlots')]))
    guard(math('Greater_IntInt',length,ex('IntConst',Value=0)))
    # Enumerate both matching equipment slots. Quickslots are not equipment
    # slots, so consumables/materials never enter this path. Empty ring slots
    # collapse independently, including an empty first slot with a full second.
    for i in range(2):
        guard(math('Greater_IntInt',copy.deepcopy(length),ex('IntConst',Value=i)))
        body.append(ctx(ex('ObjectConst',Value=a.imp('Default__KismetArrayLibrary')),
            ex('FinalFunction',StackNode=a.imp('Array_Get'),
               Parameters=[local('ValidSlots'),ex('IntConst',Value=i),local('EquipmentSlot')])))
        body.append(store('EquippedHandle',ctx(local('Inventory'),
            ex('FinalFunction',StackNode=a.imp('GetEquippedItem'),
               Parameters=[local('EquipmentSlot'),ex('IntConst',Value=-1),ex('True')]),ptr('EquippedHandle',fn_owner))))
        skip=ex('JumpIfNot',CodeOffset=0,BooleanExpression=valid_handle(local('EquippedHandle')))
        body.append(skip)
        # Each equipped card compares to its own slot, suppressing misleading
        # deltas between the two equipped rings. The left card keeps stock deltas.
        child=var(f'IC_EquippedTooltip{i}',owner)
        body.append(ex('Let',Value=ptr('IntemSlotComparedTo',stock_class),
            Variable=ctx(child,var('IntemSlotComparedTo',stock_class),ptr('IntemSlotComparedTo',stock_class)),
            Expression=ex('IntConst',Value=i)))
        body.append(ctx(child,call('Set Item',local('EquippedHandle'),ex('IntConst',Value=1),ex('False'),ex('NoObject'))))
        # Stock Set Item registers the tooltip's native scroll input processor.
        # Equipped cards are passive: release their processor synchronously,
        # before opening the popup, without touching the primary tooltip's.
        body.append(ctx(child,ex('FinalFunction',StackNode=a.imp('DeregisterInputProcessor'),Parameters=[])))
        body += [visible(3,f'IC_Group{i}'),visible(3),found(True)]
        skip['CodeOffset']=sum(map(size,body))
    end=sum(map(size,body))
    for branch in branches: branch['CodeOffset']=end
    # Open once, after both cards have refreshed. All early exits converge here
    # so a valid first slot still opens when there is no second matching slot.
    no_popup=ex('JumpIfNot',CodeOffset=0,BooleanExpression=local('HasComparison'))
    body += [no_popup,popup(True)]
    no_popup['CodeOffset']=sum(map(size,body))
    body += [ex('Return',ReturnExpression=ex('Nothing')),ex('EndOfScript')]
    fn=copy.deepcopy(a.export('OnInitialized'))
    fn.update(ObjectName=fn_name,FunctionFlags='FUNC_Public, FUNC_BlueprintCallable, FUNC_HasDefaults',
              SuperStruct=0,SuperIndex=0,LoadedProperties=locals_,ScriptBytecode=body,
              ScriptBytecodeSize=sum(map(size,body)),SerialSize=0,SerialOffset=0,
              SerializationBeforeSerializationDependencies=[],CreateBeforeSerializationDependencies=[])
    assert a.append(fn)==fn_owner
    cls['FuncMap'].append([fn_name,fn_owner]); cls['Children'].append(fn_owner)
    cls['CreateBeforeSerializationDependencies'].append(fn_owner)

    content_name='IC_GetComparisonContent'
    content_owner=len(a.data['Exports'])+1
    return_prop=copy.deepcopy(next(p for p in a.export('Get User Inventory Component')['LoadedProperties']
        if p['Name']=='ReturnValue'))
    return_prop['PropertyClass']=widget_class
    content_body=[ctx(var('IC_Stack',owner),ex('FinalFunction',StackNode=remove_from_parent,Parameters=[])),
        ex('Return',ReturnExpression=var('IC_Stack',owner)),ex('EndOfScript')]
    content_fn=copy.deepcopy(fn)
    content_fn.update(ObjectName=content_name,LoadedProperties=[return_prop],ScriptBytecode=content_body,
        ScriptBytecodeSize=sum(map(size,content_body)))
    assert a.append(content_fn)==content_owner
    cls['FuncMap'].append([content_name,content_owner]); cls['Children'].append(content_owner)
    cls['CreateBeforeSerializationDependencies'].append(content_owner)
    # UMenuAnchor's legacy UWidget-returning delegate is retained by UE5.5 and
    # lets the existing native VerticalBox be popup content without a new asset.
    cls['Data'].append(prop('Bindings',[struct('0','DelegateRuntimeBinding',[
        prop('ObjectName','IC_PopupAnchor','Objects.StrPropertyData'),
        prop('PropertyName','OnGetMenuContentEvent','Objects.NamePropertyData'),
        prop('FunctionName',content_name,'Objects.NamePropertyData'),
        enum('Kind','EBindingKind','Function')])],
        'Objects.ArrayPropertyData',ArrayType='StructProperty'))
    for name in ('Set Item','SetComparedItemSlot'):
        fn=a.export(name)
        assert fn['ScriptBytecode'][-2]['$type'].split('EX_')[1].startswith('Return,')
        fn['ScriptBytecode'].insert(-2,call(fn_name))
        fn['ScriptBytecodeSize']=sum(map(size,fn['ScriptBytecode']))
    # The main tooltip remains the only native input recipient. Forward its
    # already-filtered scroll delta to visible stock cards, which clamp their
    # own offsets independently. Never re-register passive input processors.
    scroll=a.export('OnScrolled')
    scroll_owner=a.index('OnScrolled')
    scroll_body=scroll['ScriptBytecode'][:-2]
    is_open=a.add_import('IsOpen',anchor_class)
    closed=ex('JumpIfNot',CodeOffset=0,BooleanExpression=ctx(var('IC_PopupAnchor',owner),
        ex('FinalFunction',StackNode=is_open,Parameters=[])))
    scroll_body.append(closed)
    for i in range(2):
        shown=ex('CallMath',StackNode=a.imp('EqualEqual_ByteByte'),Parameters=[
            ctx(var(f'IC_Group{i}',owner),ex('FinalFunction',StackNode=a.imp('GetVisibility'),Parameters=[])),
            ex('ByteConst',Value=3)])
        skip=ex('JumpIfNot',CodeOffset=0,BooleanExpression=shown)
        scroll_body.append(skip)
        scroll_body.append(ctx(var(f'IC_EquippedTooltip{i}',owner),
            call('OnScrolled',var('Value',scroll_owner,local=True))))
        skip['CodeOffset']=sum(map(size,scroll_body))
    closed['CodeOffset']=sum(map(size,scroll_body))
    scroll['ScriptBytecode']=scroll_body+scroll['ScriptBytecode'][-2:]
    scroll['ScriptBytecodeSize']=sum(map(size,scroll['ScriptBytecode']))
    # Invalid hover and panel teardown use the stock fade path.
    fn=a.export('Fade Out')
    fn['ScriptBytecode'][:0]=[popup(False),visible(1)]
    fn['ScriptBytecodeSize']=sum(map(size,fn['ScriptBytecode']))
    from localization_mod import add_localized_header
    add_localized_header(a, variant)
    a.names()

    panel = read(ROOT/'decoded/panel.json')
    # Only the inventory panel instantiates the private comparison tooltip.
    # Preserve the public member name and the complete panel property schema.
    old_path = '/Game/_Dawnwalker/UI/_Unified/GameHub/Inventory/Tooltip/'+ORIGINAL
    for imp in panel['Imports']:
        if imp['ObjectName'] in (old_path, ORIGINAL+'_C', 'Default__'+ORIGINAL+'_C'):
            imp['ObjectName']=imp['ObjectName'].replace(ORIGINAL,PRIVATE)
        if imp['ClassPackage']==old_path: imp['ClassPackage']=old_path.replace(ORIGINAL,PRIVATE)
        if imp['ClassName']==ORIGINAL+'_C': imp['ClassName']=PRIVATE+'_C'
    p=Asset(panel)
    # The inner comparison wrapper alone does not isolate the primary card's
    # ScaleBox. Its changing desired size can still feed the shared inventory
    # grid. Reserve the unscaled stock card width outside that ScaleBox and let
    # the inventory determine row height. Fill slots still give the tooltip
    # real geometry, so tall cards keep the stock DownOnly scaling behavior.
    tooltip_box=p.export('Tooltip')
    getprop(tooltip_box,'WidthOverride')['Value']=getprop(a.export('SizeBox_0'),'WidthOverride')['Value']
    tooltip_box['Data'] += [prop('bOverride_WidthOverride',True,'Objects.BoolPropertyData'),
        prop('HeightOverride',0.0,'Objects.FloatPropertyData'),
        prop('bOverride_HeightOverride',True,'Objects.BoolPropertyData')]
    for slot_name in ('GridSlot_3','SizeBoxSlot_0'):
        p.export(slot_name)['Data'] += copy.deepcopy(fill)
    p.names()
    return a.data,p.data


def run(*args):
    subprocess.run(list(map(str,args)),cwd=ROOT,check=True,creationflags=subprocess.CREATE_NO_WINDOW)


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--variant',choices=VARIANTS,default='default')
    args=parser.parse_args()
    assert (SOURCE_ROOT/'tools/Data/Mappings'/(MAPPING+'.usmap')).is_file(), 'Prepare fresh Dawnwalker 1.1 mappings before building'
    assert (ROOT/'input-provenance.json').is_file(), 'Run prepare_patch11.py with fresh mappings before building'
    work,dist=release_paths(args.variant)
    if work != ROOT:
        # Unversioned Blueprint serialization resolves schemas from adjacent
        # reference assets. Supply local working copies for the isolated build.
        shutil.copytree(ROOT/'reference-stage', work/'extracted', dirs_exist_ok=True)
    primary,panel=build_assets(args.variant)
    from storage_mod import build_storage_assets
    assets=[(primary,UI/'Tooltip'/f'{PRIVATE}.uasset'),(panel,UI/'WBP_InventoryPanel.uasset')]
    assets.extend(build_storage_assets(primary))
    stage=work/'staging'
    gui=SOURCE_ROOT/'tools/UAssetGUI.exe'
    retoc=SOURCE_ROOT/'tools/retoc.exe'
    sources=[]
    for asset,rel in assets:
        source=(work/'extracted'/rel).with_suffix('.json')
        write(source,asset)
        target=work/'extracted'/rel
        # UAssetGUI may report conversion errors through its UI and still exit
        # zero. Never accept an artifact left behind by an earlier build.
        for suffix in ('.uasset','.uexp'): target.with_suffix(suffix).unlink(missing_ok=True)
        run(gui,'fromjson',source,target,MAPPING)
        assert target.exists() and target.with_suffix('.uexp').exists(), f'Conversion failed: {target}'
        dest=stage/rel
        dest.parent.mkdir(parents=True,exist_ok=True)
        for suffix in ('.uasset','.uexp'): dest.with_suffix(suffix).write_bytes(target.with_suffix(suffix).read_bytes())
        sources.append((source,rel))
    dist.mkdir(parents=True,exist_ok=True)
    run(retoc,'to-zen',stage,dist/(STEM+'.utoc'),'--version','UE5_5')
    run(retoc,'verify',dist/(STEM+'.utoc'))
    write(work/'build-manifest.json',{'version':VERSION,'variant':args.variant,'assets':[str(p) for _,p in sources],
        'payloads':{p.name:hashlib.sha256(p.read_bytes()).hexdigest() for p in dist.glob(STEM+'.*')}})
    print(f'Built {dist}; run verify_mod.py before packaging.')


if __name__=='__main__': main()
